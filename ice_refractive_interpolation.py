# Extract data columns
_WAVELENGTHS = _ICE_DATA[:, 0]   # wavelength μm
_N_VALUES = _ICE_DATA[:, 1]      # real part n
_K_VALUES = _ICE_DATA[:, 2]      # imaginary part k

# Create interpolation function
_n_interp = interp1d(_WAVELENGTHS, _N_VALUES, kind='linear', fill_value="extrapolate")
_k_interp = interp1d(_WAVELENGTHS, _K_VALUES, kind='linear', fill_value="extrapolate")

# FY-3D MERSI2  central wavelengths (μm) 
MERSI2_BANDS = {
    5: 1.38, 6: 1.64, 7: 2.13,
    8: 0.412, 9: 0.443, 10: 0.490, 11: 0.555, 12: 0.670, 13: 0.709,
    14: 0.746, 15: 0.865, 16: 0.905, 17: 0.936, 18: 0.940, 19: 1.03
}


def get_nk(wavelength_um):
    n = _n_interp(wavelength_um)
    k = _k_interp(wavelength_um)
    return n, k


def get_alpha(wavelength_nm): 
    lam_um = wavelength_nm / 1000.0       
    k_val = _k_interp(lam_um)              
    lam_cm = wavelength_nm * 1e-7          
    alpha = 4.0 * math.pi * k_val / lam_cm
    return alpha


def get_band_nk(band_num):
    wl = MERSI2_BANDS.get(band_num)
    if wl is None:
        return None, None
    return get_nk(wl)


def print_band_table():
    print("Ice refractive indices corresponding to MERSI2 band central wavelengths (n, k)：")
    print("-" * 50)
    for band, wl in sorted(MERSI2_BANDS.items()):
        n_val, k_val = get_nk(wl)
        print(f"Band {band:2d}: λ={wl:.3f} μm, n={n_val:.4f}, k={k_val:.4e}")

def n_interp(wavelength_um):
    return _n_interp(wavelength_um)


def k_interp(wavelength_um):
    return _k_interp(wavelength_um)


def alpha(lam_nm):
    return get_alpha(lam_nm)


